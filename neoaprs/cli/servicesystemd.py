"""The service on Linux: a systemd user unit, ~/.config/systemd/user/neoaprs.service, written from the template `neoaprs.service` of this package with the interpreter that runs this and the data
folder (in an AppImage it starts the AppImage file, not the interpreter inside the mount). A unit this program did not write is never touched (its first line says who wrote it). The unit is
enabled and started, and restarted when what it runs changed; `--linger` lets it start at boot and survive a logout. A user must be in the group that owns the serial devices: it is checked and the
command that cures it is said."""
import getpass
import os
import re
import subprocess
import urllib.parse
from importlib import resources
from pathlib import Path

from .daemonstate import describe
from .hostcheck import serial_group_check
from .servicecmd import REPO, Plan

UNIT_NAME = "neoaprs.service"
HEADER = "# Generated by `neoaprs service install`; changes are lost the next time it runs: run it again to bring the unit up to date."
MARK = "# Generated by `neoaprs service install`"
LOG_HINT = "the journal of the service: journalctl --user -u neoaprs -f"
PLAIN = re.compile(r"[A-Za-z0-9_./+@:,=-]+")
METADATA = ("Description=", "Documentation=")           # lines that say what the unit is and change nothing it does


def unit_dir() -> Path:
    return Path(os.environ.get("XDG_CONFIG_HOME") or Path.home() / ".config") / "systemd" / "user"


def unit_path() -> Path:
    return unit_dir() / UNIT_NAME


def quote(argument: str) -> str:
    """An argument of ExecStart: as it is when it is plain, else in double quotes with the characters systemd reads inside them escaped (a backslash, a quote, and `%` and `$`, which it expands)."""
    if PLAIN.fullmatch(argument):
        return argument
    return '"' + argument.replace("\\", "\\\\").replace('"', '\\"').replace("%", "%%").replace("$", "$$") + '"'


def render(plan: Plan) -> str:
    """The unit as it is written: the template with the places filled in, under the line that says who wrote it. Without a clone there is no working directory and the documentation is the web page."""
    template = resources.files("neoaprs.cli").joinpath(UNIT_NAME).read_text(encoding="utf-8")
    if plan.clone is not None:
        folder = str(plan.clone)
        documentation = "file://" + (folder if PLAIN.fullmatch(folder) else urllib.parse.quote(folder).replace("%", "%%")) + "/README.md"
    else:
        folder, documentation = "", REPO
    command = quote(plan.appimage) if plan.appimage else f"{quote(plan.python)} -m neoaprs"
    body = []
    for line in template.splitlines():
        if "@WORKING_DIRECTORY@" in line and plan.clone is None:
            continue
        body.append(line.replace("@WORKING_DIRECTORY@", folder.replace("%", "%%")).replace("@DOCUMENTATION@", documentation)
                    .replace("@COMMAND@", command).replace("@DATA@", quote(str(plan.data))))
    return HEADER + "\n" + "\n".join(body).rstrip("\n") + "\n"


def effect(unit: str) -> list[str]:
    """What a unit does: its lines without the comments and without the lines of metadata, so that a changed comment is no reason to restart a running service."""
    return [line.strip() for line in unit.splitlines() if line.strip() and not line.lstrip().startswith("#") and not line.startswith(METADATA)]


def written_by_us(path: Path) -> bool:
    """A file (not a link) whose first line is one of ours."""
    if path.is_symlink() or not path.is_file():
        return False
    try:
        first = path.read_text(encoding="utf-8", errors="replace").split("\n", 1)[0]
    except OSError:
        return False
    return first.startswith(MARK)


def installed(plan: Plan) -> tuple[bool, str]:
    path = unit_path()
    if written_by_us(path):
        return True, f"the user unit {path}"
    return False, "no user unit" if not (path.exists() or path.is_symlink()) else f"{path} exists but was not written by neoaprs"


def systemctl(*args: str) -> int:
    """`systemctl --user ...`; its output goes to the terminal. -1 when there is no systemctl."""
    try:
        return subprocess.run(["systemctl", "--user", *args], check=False).returncode
    except FileNotFoundError:
        print("systemctl was not found: this computer does not run systemd, so there is no user service to set up; run `neoaprs run` from your session's autostart instead")
        return -1


def ask(*command: str) -> str:
    """The standard output of a command, '' when it cannot be run or fails."""
    try:
        done = subprocess.run(command, capture_output=True, text=True, check=False)
    except OSError:
        return ""
    return done.stdout.strip() if done.returncode == 0 else ""


def user_name() -> str:
    return os.environ.get("USER") or getpass.getuser()


def install(plan: Plan) -> int:
    path = unit_path()
    unit = render(plan)
    restart = False
    if path.exists() or path.is_symlink():
        if not written_by_us(path):
            print(f"{path} exists and was not written by neoaprs; move it away (or `neoaprs service remove` after checking it) and run this again")
            return 1
        restart = effect(path.read_text(encoding="utf-8")) != effect(unit)
    plan.data.mkdir(parents=True, exist_ok=True)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists() or path.read_text(encoding="utf-8") != unit:
        scratch = path.with_name(path.name + ".new")
        scratch.write_text(unit, encoding="utf-8")
        scratch.replace(path)
        print(f"wrote {path} for {plan.clone or plan.appimage or plan.python}")
    for step in (("daemon-reload",), ("enable", "--now", UNIT_NAME)):
        code = systemctl(*step)
        if code != 0:
            if code > 0:
                print("systemctl did not accept the unit; is there a user session (`systemctl --user status` must work in this terminal)?")
            return 1
    if restart and systemctl("try-restart", UNIT_NAME) == 0:
        print("the unit changed: the service was restarted")
    after_install(plan)
    return 0


def after_install(plan: Plan) -> None:
    user = user_name()
    if plan.linger:
        try:
            enabled = subprocess.run(["loginctl", "enable-linger", user], check=False).returncode == 0
        except FileNotFoundError:
            enabled = False
        if not enabled:
            print(f"note: 'loginctl enable-linger {user}' needs to be run once so that neoaprs starts at boot without a login")
    elif ask("loginctl", "show-user", user, "--property=Linger") != "Linger=yes":
        print(f"note: it runs while you are logged in; to start at boot without a login run once: loginctl enable-linger {user}   (or `neoaprs service install --linger`)")
    group = serial_group_check()
    if group.status in ("missing", "relogin"):
        print(f"note: {user} cannot open the radio's serial port yet: {group.fix}")
    print(f"neoaprs runs (journal: journalctl --user -u neoaprs -f; log: {plan.data / 'neoaprs.log'}); the page is on http://127.0.0.1:7303 (the setting web/port)")


def remove(plan: Plan) -> int:
    path = unit_path()
    exists = path.exists() or path.is_symlink()
    ours = written_by_us(path)
    if exists and not ours:
        print(f"{path} was not written by neoaprs; nothing was changed")
        return 1
    systemctl("disable", "--now", UNIT_NAME)
    if ours:
        path.unlink()
        print(f"removed {path}")
    systemctl("daemon-reload")
    print("neoaprs is no longer a service; the data folder is untouched")
    return 0


def status(plan: Plan) -> int:
    is_set, what = installed(plan)
    print(f"service: {'set up: ' + what if is_set else 'not set up (' + what + ')'}")
    active = False
    if is_set:
        enabled = ask("systemctl", "--user", "is-enabled", UNIT_NAME) or "unknown"
        state = ask("systemctl", "--user", "is-active", UNIT_NAME) or "not active"
        active = state == "active"
        print(f"systemd: {state}, {enabled}")
    running, line = describe(plan.data)
    print(f"daemon: {line}")
    if not is_set:
        print("set it up with: neoaprs service install")
    return 0 if is_set and active and running else 1
