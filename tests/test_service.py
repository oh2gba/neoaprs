def test_the_unit_has_the_effect_of_the_reference_unit(linux: Linux, capsys: pytest.CaptureFixture[str]) -> None:
    assert linux.run("install") == 0
    text = linux.unit.read_text(encoding="utf-8")
    assert not linux.unit.is_symlink() and "@PYTHON@" not in text and "@DATA@" not in text and "@WORKING" not in text and text.startswith("# Generated by `neoaprs service install`")
    wrote = servicesystemd.effect(text)
    reference = servicesystemd.effect(reference_unit(linux.clone))
    reference_start = f"ExecStart={linux.clone}/.venv/bin/python -m neoaprs --data {linux.clone}/data"
    assert reference_start in reference and f"WorkingDirectory={linux.clone}" in reference
    assert wrote == [line.replace(reference_start, f"ExecStart={sys.executable} -m neoaprs --data {linux.clone}/data") for line in reference], "what the unit does is what the reference unit does, with this interpreter in place of the clone's venv"
    assert f"Documentation=file://{linux.clone}/README.md" in text and (linux.clone / "data").is_dir()
    assert linux.calls() == ["systemctl --user daemon-reload", "systemctl --user enable --now neoaprs.service"]
    assert "wrote" in capsys.readouterr().out


