REFERENCE_TEMPLATE = (ROOT / "tests" / "fixtures" / "service" / "reference-unit.template").read_text(encoding="utf-8")       # the unit of a clone, written by hand
FOREIGN = "[Unit]\nDescription=foreign\n[Service]\nExecStart=/other/.venv/bin/python -m neoaprs\n"
REFERENCE_HEADER = "# Generated by `neoaprs service install`; changes are lost the next time it runs: run it again to bring the unit up to date."


def reference_unit(clone: Path) -> str:
    """The unit written by hand for a clone: the marker line, then the reference template with @ROOT@ replaced."""
    return REFERENCE_HEADER + "\n" + REFERENCE_TEMPLATE.replace("@ROOT@", str(clone)).rstrip("\n") + "\n"


class Linux:
    """A Linux user: a clone, a HOME, the fake tools."""

    def __init__(self, tmp_path: Path, monkeypatch: pytest.MonkeyPatch, folder: str = "clone") -> None:
        self.clone = tmp_path / folder
        self.clone.mkdir()
        self.home = tmp_path / "home"
        self.home.mkdir()
        self.tools = FakeTools(tmp_path / "bin", tmp_path / "calls")
        self.monkeypatch = monkeypatch
        monkeypatch.setenv("HOME", str(self.home))
        monkeypatch.setenv("USER", "tester")
        monkeypatch.delenv("XDG_CONFIG_HOME", raising=False)
        monkeypatch.setattr(servicesystemd, "serial_group_check", lambda: GroupCheck("ok", "dialout", ""))
        self.tools.use(monkeypatch)
        self.unit = self.home / ".config" / "systemd" / "user" / "neoaprs.service"

    def run(self, *args: str) -> int:
        return servicecmd.main([args[0], "--data", str(self.clone / "data"), "--clone", str(self.clone), *args[1:]], platform="linux")

    def calls(self) -> list[str]:
        return self.tools.calls("systemctl ")


